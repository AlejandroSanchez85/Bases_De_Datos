-- =====================================================================
-- BogoTickets · 01 · Tablas, restricciones e índices
-- Ejecutar conectado a la base bogotickets (ver README).
-- Se puede volver a ejecutar: el DROP del inicio reinicia todas las tablas.
-- =====================================================================

DROP TABLE IF EXISTS historial_precios, boleta, compra, precio_localidad, cliente, empleado,
                     ciudad, departamento, pais, evento, tipo_evento, localidad, escenario CASCADE;


-- Recinto donde se realizan los eventos
CREATE TABLE escenario (
    id_escenario      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(100) NOT NULL,
    direccion         VARCHAR(150) NOT NULL,
    capacidad_maxima  INTEGER      NOT NULL,
    CONSTRAINT pk_escenario            PRIMARY KEY (id_escenario),
    CONSTRAINT uq_escenario_nombre     UNIQUE (nombre),
    CONSTRAINT chk_escenario_nombre    CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_escenario_direccion CHECK (TRIM(direccion) <> ''),
    CONSTRAINT chk_escenario_capacidad CHECK (capacidad_maxima > 0)          -- RN-03
);

-- Zona de un escenario con aforo propio (VIP, Platea, Gramilla...)
CREATE TABLE localidad (
    id_localidad  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_escenario  INTEGER     NOT NULL,
    nombre        VARCHAR(50) NOT NULL,
    aforo_maximo  INTEGER     NOT NULL,
    CONSTRAINT pk_localidad PRIMARY KEY (id_localidad),
    CONSTRAINT fk_localidad_escenario FOREIGN KEY (id_escenario)
        REFERENCES escenario (id_escenario) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_localidad_escenario_nombre UNIQUE (id_escenario, nombre),
    CONSTRAINT chk_localidad_nombre CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_localidad_aforo  CHECK (aforo_maximo > 0)                 -- RN-04
);

-- Clasificación del catálogo (Concierto, Deporte, Teatro...)
CREATE TABLE tipo_evento (
    id_tipo_evento  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(40)  NOT NULL,
    descripcion     VARCHAR(150),
    CONSTRAINT pk_tipo_evento        PRIMARY KEY (id_tipo_evento),
    CONSTRAINT uq_tipo_evento_nombre UNIQUE (nombre),
    CONSTRAINT chk_tipo_evento_nombre CHECK (TRIM(nombre) <> '')
);

-- Función programada en un escenario. edad_minima: 0 = todo público (RN-25)
CREATE TABLE evento (
    id_evento       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_escenario    INTEGER      NOT NULL,                                   -- RN-02
    id_tipo_evento  INTEGER      NOT NULL,                                   -- RN-21
    nombre          VARCHAR(150) NOT NULL,
    fecha           DATE         NOT NULL,
    hora_inicio     TIME         NOT NULL,
    hora_fin        TIME         NOT NULL,
    edad_minima     INTEGER      NOT NULL DEFAULT 0,
    fecha_registro  DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_escenario FOREIGN KEY (id_escenario)
        REFERENCES escenario (id_escenario) ON DELETE RESTRICT ON UPDATE CASCADE,   -- RN-14
    CONSTRAINT fk_evento_tipo FOREIGN KEY (id_tipo_evento)
        REFERENCES tipo_evento (id_tipo_evento) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_evento_escenario_fecha_hora UNIQUE (id_escenario, fecha, hora_inicio), -- RN-13
    CONSTRAINT chk_evento_nombre         CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_evento_fecha          CHECK (fecha >= fecha_registro),    -- RN-11
    CONSTRAINT chk_evento_fecha_registro CHECK (fecha_registro <= CURRENT_DATE),
    CONSTRAINT chk_evento_horario        CHECK (hora_fin > hora_inicio),     -- RN-22
    CONSTRAINT chk_evento_edad_minima    CHECK (edad_minima BETWEEN 0 AND 18)
);

-- Tarifa de una localidad en un evento (N:M evento - localidad)
CREATE TABLE precio_localidad (
    id_evento     INTEGER       NOT NULL,
    id_localidad  INTEGER       NOT NULL,
    precio        NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_precio_localidad PRIMARY KEY (id_evento, id_localidad),
    CONSTRAINT fk_precio_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_precio_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT chk_precio_valor CHECK (precio >= 0)                          -- RN-06
);

-- País, departamento y ciudad de residencia. La persona guarda solo su ciudad:
-- el departamento y el país se obtienen siguiendo las FK. Si se guardaran los
-- tres nombres en cliente, departamento dependería de ciudad y no de la llave
-- del cliente, lo que rompe la 3FN.
CREATE TABLE pais (
    id_pais     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(60) NOT NULL,
    indicativo  VARCHAR(5)  NOT NULL,                                        -- +57, +1...
    CONSTRAINT pk_pais PRIMARY KEY (id_pais),
    CONSTRAINT uq_pais_nombre UNIQUE (nombre),
    CONSTRAINT chk_pais_nombre     CHECK (TRIM(nombre) <> ''),
    CONSTRAINT chk_pais_indicativo CHECK (indicativo ~ '^[+][0-9]{1,4}$')
);

-- Departamento, o estado o provincia según el país
CREATE TABLE departamento (
    id_departamento  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_pais          INTEGER     NOT NULL,
    nombre           VARCHAR(60) NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
    CONSTRAINT fk_departamento_pais FOREIGN KEY (id_pais)
        REFERENCES pais (id_pais) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_departamento_pais_nombre UNIQUE (id_pais, nombre),
    CONSTRAINT chk_departamento_nombre CHECK (TRIM(nombre) <> '')
);

-- Ciudad o municipio
CREATE TABLE ciudad (
    id_ciudad        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_departamento  INTEGER     NOT NULL,
    nombre           VARCHAR(60) NOT NULL,
    CONSTRAINT pk_ciudad PRIMARY KEY (id_ciudad),
    CONSTRAINT fk_ciudad_departamento FOREIGN KEY (id_departamento)
        REFERENCES departamento (id_departamento) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT uq_ciudad_departamento_nombre UNIQUE (id_departamento, nombre),
    CONSTRAINT chk_ciudad_nombre CHECK (TRIM(nombre) <> '')
);

-- Comprador registrado. Inicia sesión en la aplicación con su correo y contraseña.
-- Tipos de documento: CC cédula de ciudadanía, TI tarjeta de identidad, CE cédula
-- de extranjería, PA pasaporte, PPT permiso por protección temporal.
-- La fecha de nacimiento sirve para las restricciones de edad de los eventos (RN-25).
CREATE TABLE cliente (
    id_cliente        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo_documento    VARCHAR(3)   NOT NULL,
    numero_documento  VARCHAR(20)  NOT NULL,
    nombres           VARCHAR(60)  NOT NULL,
    apellidos         VARCHAR(60)  NOT NULL,
    fecha_nacimiento  DATE         NOT NULL,
    genero            VARCHAR(10)  NOT NULL,
    correo            VARCHAR(120) NOT NULL,
    indicativo        VARCHAR(5)   NOT NULL DEFAULT '+57',
    celular           VARCHAR(15)  NOT NULL,
    id_ciudad         INTEGER      NOT NULL,
    direccion         VARCHAR(150) NOT NULL,
    contrasena        VARCHAR(100) NOT NULL,
    fecha_registro    DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_ciudad FOREIGN KEY (id_ciudad)
        REFERENCES ciudad (id_ciudad) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, numero_documento),  -- RN-09
    CONSTRAINT uq_cliente_correo    UNIQUE (correo),                             -- RN-10
    CONSTRAINT chk_cliente_tipo_documento CHECK (tipo_documento IN ('CC', 'TI', 'CE', 'PA', 'PPT')),
    CONSTRAINT chk_cliente_documento  CHECK (numero_documento ~ '^[0-9A-Z]{5,20}$'),
    CONSTRAINT chk_cliente_nombres    CHECK (TRIM(nombres) <> ''),
    CONSTRAINT chk_cliente_apellidos  CHECK (TRIM(apellidos) <> ''),
    -- Al crear la cuenta tenía al menos 14 años (RN-26). Compara dos columnas de la
    -- fila, así el resultado no cambia con el paso del tiempo.
    CONSTRAINT chk_cliente_nacimiento
        CHECK (fecha_nacimiento >= DATE '1900-01-01'
               AND fecha_nacimiento <= fecha_registro - INTERVAL '14 years'),
    -- El documento corresponde a la edad (RN-27): la CC es de mayores de 18 años y la
    -- TI de quienes eran menores al registrarse. Ninguna de las dos deja de cumplirse
    -- con los años: un adulto sigue siendo adulto y la fecha de registro no cambia.
    CONSTRAINT chk_cliente_cc_mayor_edad
        CHECK (tipo_documento <> 'CC' OR fecha_nacimiento <= CURRENT_DATE - INTERVAL '18 years'),
    CONSTRAINT chk_cliente_ti_menor_edad
        CHECK (tipo_documento <> 'TI' OR fecha_nacimiento > fecha_registro - INTERVAL '18 years'),
    CONSTRAINT chk_cliente_genero     CHECK (genero IN ('MASCULINO', 'FEMENINO', 'OTRO')),
    CONSTRAINT chk_cliente_correo
        CHECK (correo ~ '^[a-z0-9._%+-]+@[a-z0-9.-]+[.][a-z]{2,}$'),
    CONSTRAINT chk_cliente_correo_dominio
        CHECK (correo NOT LIKE '%@bogotickets.co'),                         -- RN-24
    CONSTRAINT chk_cliente_indicativo CHECK (indicativo ~ '^[+][0-9]{1,4}$'),
    CONSTRAINT chk_cliente_celular    CHECK (celular ~ '^[0-9]{7,15}$'),
    CONSTRAINT chk_cliente_direccion  CHECK (TRIM(direccion) <> ''),
    -- Solo se acepta un hash BCrypt: la contraseña nunca se guarda en texto plano (RN-23)
    CONSTRAINT chk_cliente_contrasena
        CHECK (contrasena ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
    CONSTRAINT chk_cliente_fecha_registro CHECK (fecha_registro <= CURRENT_DATE)
);

-- Empleado de BogoTickets que entra a la aplicación: administrador de escenarios
-- y eventos o analista de ventas. Guarda los mismos datos personales que el
-- cliente; sus correos son del dominio de la empresa (RN-24) y es mayor de edad.
CREATE TABLE empleado (
    id_empleado       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo_documento    VARCHAR(3)   NOT NULL,
    numero_documento  VARCHAR(20)  NOT NULL,
    nombres           VARCHAR(60)  NOT NULL,
    apellidos         VARCHAR(60)  NOT NULL,
    fecha_nacimiento  DATE         NOT NULL,
    genero            VARCHAR(10)  NOT NULL,
    correo            VARCHAR(120) NOT NULL,
    indicativo        VARCHAR(5)   NOT NULL DEFAULT '+57',
    celular           VARCHAR(15)  NOT NULL,
    id_ciudad         INTEGER      NOT NULL,
    direccion         VARCHAR(150) NOT NULL,
    contrasena        VARCHAR(100) NOT NULL,
    rol               VARCHAR(15)  NOT NULL,
    fecha_registro    DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_empleado PRIMARY KEY (id_empleado),
    CONSTRAINT fk_empleado_ciudad FOREIGN KEY (id_ciudad)
        REFERENCES ciudad (id_ciudad) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT uq_empleado_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT uq_empleado_correo    UNIQUE (correo),
    CONSTRAINT chk_empleado_tipo_documento CHECK (tipo_documento IN ('CC', 'CE', 'PA', 'PPT')),
    CONSTRAINT chk_empleado_documento  CHECK (numero_documento ~ '^[0-9A-Z]{5,20}$'),
    CONSTRAINT chk_empleado_nombres    CHECK (TRIM(nombres) <> ''),
    CONSTRAINT chk_empleado_apellidos  CHECK (TRIM(apellidos) <> ''),
    CONSTRAINT chk_empleado_nacimiento                                      -- mayor de edad al ingresar
        CHECK (fecha_nacimiento >= DATE '1900-01-01'
               AND fecha_nacimiento <= fecha_registro - INTERVAL '18 years'),
    CONSTRAINT chk_empleado_genero     CHECK (genero IN ('MASCULINO', 'FEMENINO', 'OTRO')),
    CONSTRAINT chk_empleado_correo     CHECK (correo ~ '^[a-z0-9._%+-]+@bogotickets[.]co$'),
    CONSTRAINT chk_empleado_indicativo CHECK (indicativo ~ '^[+][0-9]{1,4}$'),
    CONSTRAINT chk_empleado_celular    CHECK (celular ~ '^[0-9]{7,15}$'),
    CONSTRAINT chk_empleado_direccion  CHECK (TRIM(direccion) <> ''),
    CONSTRAINT chk_empleado_contrasena
        CHECK (contrasena ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),     -- RN-23
    CONSTRAINT chk_empleado_rol CHECK (rol IN ('ADMINISTRADOR', 'ANALISTA')),
    CONSTRAINT chk_empleado_fecha_registro CHECK (fecha_registro <= CURRENT_DATE)
);

-- Transacción de compra de un cliente (agrupa sus boletas)
CREATE TABLE compra (
    id_compra     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    INTEGER     NOT NULL,
    fecha_compra  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metodo_pago   VARCHAR(10) NOT NULL DEFAULT 'TARJETA',
    CONSTRAINT pk_compra PRIMARY KEY (id_compra),
    CONSTRAINT fk_compra_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_compra_fecha  CHECK (fecha_compra <= CURRENT_TIMESTAMP),  -- RNF-03
    CONSTRAINT chk_compra_metodo CHECK (metodo_pago IN ('TARJETA', 'PSE', 'EFECTIVO'))
);

-- Entrada vendida: una boleta = un cupo de una localidad en un evento.
-- La FK compuesta obliga a que la localidad tenga precio en ese evento (RN-08).
CREATE TABLE boleta (
    id_boleta      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_compra      INTEGER       NOT NULL,
    id_evento      INTEGER       NOT NULL,
    id_localidad   INTEGER       NOT NULL,
    precio_pagado  NUMERIC(12,2) NOT NULL,                                   -- RN-16
    estado         VARCHAR(10)   NOT NULL DEFAULT 'Vendida',
    CONSTRAINT pk_boleta PRIMARY KEY (id_boleta),
    CONSTRAINT fk_boleta_compra FOREIGN KEY (id_compra)
        REFERENCES compra (id_compra) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_boleta_precio_localidad FOREIGN KEY (id_evento, id_localidad)
        REFERENCES precio_localidad (id_evento, id_localidad)
        ON DELETE RESTRICT ON UPDATE RESTRICT,                               -- RN-14
    CONSTRAINT chk_boleta_precio CHECK (precio_pagado >= 0),
    CONSTRAINT chk_boleta_estado CHECK (estado IN ('Vendida', 'Cancelada'))  -- RNF-07
);

-- Auditoría de cambios de precio y de aforo (RNF-06).
-- PRECIO lleva id_evento; AFORO_MAXIMO no (el aforo es de la localidad).
-- usuario: si el cambio llega por la API es el correo del empleado (la API lo
-- deja en la variable bogotickets.usuario de la transacción); desde pgAdmin,
-- el usuario de PostgreSQL.
CREATE TABLE historial_precios (
    id_historial      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_localidad      INTEGER       NOT NULL,
    id_evento         INTEGER,
    campo_modificado  VARCHAR(20)   NOT NULL,
    valor_anterior    NUMERIC(12,2) NOT NULL,
    valor_nuevo       NUMERIC(12,2) NOT NULL,
    usuario           VARCHAR(120)  NOT NULL
                      DEFAULT COALESCE(NULLIF(current_setting('bogotickets.usuario', true), ''), CURRENT_USER),
    fecha_cambio      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_historial_precios PRIMARY KEY (id_historial),
    CONSTRAINT fk_historial_localidad FOREIGN KEY (id_localidad)
        REFERENCES localidad (id_localidad) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_historial_evento FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_historial_campo CHECK (campo_modificado IN ('PRECIO', 'AFORO_MAXIMO')),
    CONSTRAINT chk_historial_coherencia CHECK (
        (campo_modificado = 'PRECIO'       AND id_evento IS NOT NULL) OR
        (campo_modificado = 'AFORO_MAXIMO' AND id_evento IS NULL)),
    CONSTRAINT chk_historial_valores CHECK (valor_anterior >= 0 AND valor_nuevo >= 0),
    CONSTRAINT chk_historial_cambio  CHECK (valor_anterior <> valor_nuevo),
    CONSTRAINT chk_historial_usuario CHECK (TRIM(usuario) <> '')
);


-- Índices para las FK más consultadas y las búsquedas del catálogo (RNF-08, RNF-09)
CREATE INDEX idx_evento_fecha         ON evento (fecha);
CREATE INDEX idx_evento_tipo          ON evento (id_tipo_evento);
CREATE INDEX idx_precio_localidad_loc ON precio_localidad (id_localidad);
CREATE INDEX idx_cliente_ciudad       ON cliente (id_ciudad);
CREATE INDEX idx_compra_cliente       ON compra (id_cliente);
CREATE INDEX idx_boleta_compra        ON boleta (id_compra);
CREATE INDEX idx_boleta_tarifa        ON boleta (id_evento, id_localidad);
CREATE INDEX idx_historial_localidad  ON historial_precios (id_localidad);
CREATE INDEX idx_historial_evento     ON historial_precios (id_evento);


-- Verificación: las 13 tablas y cuántas restricciones tiene cada una
SELECT c.relname AS tabla,
       COUNT(k.oid) AS restricciones
FROM   pg_class c
LEFT   JOIN pg_constraint k ON k.conrelid = c.oid AND k.contype IN ('p', 'f', 'u', 'c')
WHERE  c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
GROUP  BY c.relname
ORDER  BY c.relname;
